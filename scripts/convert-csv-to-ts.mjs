#!/usr/bin/env node
/**
 * Converts the raw synthetic-data CSVs in data-source/data/ into typed
 * TypeScript modules under src/data/generated/.
 *
 * Why this exists (see conversation history / integration plan):
 *  - There is no backend for this prototype, and the dataset is static.
 *  - Parsing CSV in the browser at runtime (e.g. with papaparse) would add
 *    a dependency and a failure mode for data that never changes.
 *  - Converting once, at build/prep time, gives full TypeScript type
 *    checking and IDE autocomplete with zero runtime parsing cost.
 *
 * Usage:
 *   node scripts/convert-csv-to-ts.mjs
 *
 * Re-run this any time data-source/data/*.csv is regenerated
 * (e.g. after `python scripts/generate_data.py` in data-source/).
 *
 * Output files are marked as generated and should not be hand-edited.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const DATA_SOURCE_DIR = path.join(ROOT, "data-source", "data");
const OUT_DIR = path.join(ROOT, "src", "data", "generated");

/**
 * Minimal RFC4126-ish CSV parser: handles quoted fields, embedded commas,
 * escaped double-quotes (""), and CRLF/LF line endings. No external
 * dependency needed for a static, well-formed dataset like this one.
 */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;
  let i = 0;
  const len = text.length;

  while (i < len) {
    const c = text[i];

    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 2;
          continue;
        }
        inQuotes = false;
        i++;
        continue;
      }
      field += c;
      i++;
      continue;
    }

    if (c === '"') {
      inQuotes = true;
      i++;
      continue;
    }
    if (c === ",") {
      row.push(field);
      field = "";
      i++;
      continue;
    }
    if (c === "\r") {
      i++;
      continue;
    }
    if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
      i++;
      continue;
    }
    field += c;
    i++;
  }
  // last field/row (files may or may not end with a trailing newline)
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }

  const [header, ...dataRows] = rows;
  return dataRows
    .filter((r) => r.length === header.length && !(r.length === 1 && r[0] === ""))
    .map((r) => Object.fromEntries(header.map((h, idx) => [h, r[idx]])));
}

function readCsv(filename) {
  const text = readFileSync(path.join(DATA_SOURCE_DIR, filename), "utf-8");
  return parseCsv(text);
}

const num = (v) => (v === "" || v === undefined ? null : Number(v));
const str = (v) => (v === undefined ? "" : v);
const nullableStr = (v) => (v === "" || v === undefined ? null : v);
const bool = (v) => v === "True" || v === "true";

function toCamelKeyObject(obj, fieldMap) {
  const out = {};
  for (const [snakeKey, [camelKey, transform]] of Object.entries(fieldMap)) {
    out[camelKey] = transform(obj[snakeKey]);
  }
  return out;
}

function emitModule(varName, typeName, rows, { header = "" } = {}) {
  const body = JSON.stringify(rows, null, 2);
  return `// AUTO-GENERATED by scripts/convert-csv-to-ts.mjs — do not edit by hand.
// Source: data-source/data/*.csv. Re-run the script after regenerating CSVs.
${header}
import type { ${typeName} } from "../types";

export const ${varName}: ${typeName}[] = ${body};
`;
}

